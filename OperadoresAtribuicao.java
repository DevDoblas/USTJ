public class OperadoresAtribuicao {
   
    public static void main(String[] args) {
        System.out.println("   ");

         int x = 10;
         System.out.println(x);

         x += 5;
         System.out.println(x);
         x -= 2;
         System.out.println(x);

         x *= 5;
         System.out.println(x);

         x /= 5;
         System.out.println(x);

         x %= 5;
         System.out.println(x);

     


    }
    }
